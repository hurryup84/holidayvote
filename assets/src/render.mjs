// ---------- render ----------
const browser = await chromium.launch({ channel: 'chrome' });
const page = await browser.newPage({ deviceScaleFactor: 1 });
const rel = (p) => p.replace(root + '/', '');

async function renderSvg(content, out, size) {
  mkdirSync(dirname(out), { recursive: true });
  await page.setViewportSize({ width: size, height: size });
  await page.setContent(`<html><body style="margin:0;background:transparent">${content}</body></html>`);
  await page.locator('svg').first().evaluate((s, n) => { s.setAttribute('width', n); s.setAttribute('height', n); }, String(size));
  await page.locator('svg').first().screenshot({ path: out, omitBackground: true });
  console.log('wrote', rel(out));
}
async function renderHtml(html, w, h, out) {
  mkdirSync(dirname(out), { recursive: true });
  const tab = await browser.newPage({ deviceScaleFactor: 1, viewport: { width: w, height: h } }); // fresh tab: resizing one left stale layout
  await tab.setContent(html, { waitUntil: 'load' });
  await tab.screenshot({ path: out });
  await tab.close();
  console.log('wrote', rel(out));
}

