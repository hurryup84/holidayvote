// ---------- derived SVGs ----------
const icon = readFileSync(join(here, 'icon.svg'), 'utf8');
const defs = /<defs>[\s\S]*?<\/defs>/.exec(icon)[0];
const background = /<rect id="background"[^>]*\/>/.exec(icon)[0];
const art = /<g id="art"[\s\S]*<\/g>/.exec(icon)[0];
const svg = (size, body) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}">\n${body}\n</svg>\n`;
const around = (cx, s) => `translate(${cx} ${cx}) scale(${s}) translate(-512 -512)`;
const derived = {
  // Generated by render.mjs from icon.svg – edit icon.svg instead.
  // capacitor-assets insets the layers by 16.7 %, so this PNG is the visible 72 dp area; at 0.82 the sun and the
  // waves stay well inside the 66 dp safe zone (circle masks included).
  'icon-foreground.svg': svg(1024, `<!-- generated by render.mjs from icon.svg -->\n<g transform="${around(512, 0.82)}">${art}</g>`),
  'icon-background.svg': svg(1024, `<!-- generated by render.mjs from icon.svg -->\n${defs}\n${background}`),
  ...Object.fromEntries(
    [['splash.svg', C.sand], ['splash-dark.svg', C.night]].map(([name, bg]) => [
      name,
      svg(2732, `<!-- generated by render.mjs from icon.svg -->\n${defs}\n<rect width="2732" height="2732" fill="${bg}"/>
<clipPath id="round"><rect width="1024" height="1024" rx="230"/></clipPath>
<g transform="translate(1366 1366) scale(0.42) translate(-512 -512)" clip-path="url(#round)">${background}${art}</g>`),
    ]),
  ),
};
for (const [name, content] of Object.entries(derived)) writeFileSync(join(here, name), content);

