//
// icon.svg is the only drawing. Its <g id="art"> is reused here to (re)write
//   icon-foreground.svg (Android adaptive icon, transparent, scaled into the safe zone),
//   icon-background.svg (the teal gradient), splash.svg / splash-dark.svg (rounded icon on sand / dark).
// Output:
//   assets/icon-only.png, icon-foreground.png, icon-background.png (1024), splash.png, splash-dark.png (2732)
//     → input for `npx capacitor-assets generate` (iOS / Android icons + splash screens)
//   website/icon.png (256), website/og.png (1200 × 630 link preview)
//   android/fastlane/metadata/android/<locale>/images/featureGraphic.png (1024 × 500) and icon.png (512)
// No photos of real holiday homes anywhere – the cards in the graphics are drawn.
